import assert from 'node:assert/strict'
import { csvPreview, outputBytes, previewDocument, safeOutputName, textOutput, toolOutputs } from '../src/lib/outputFiles.js'
assert.equal(safeOutputName('../../report.html'), 'report.html')
assert.equal(safeOutputName('CON.txt'), 'output.txt')
assert.equal(safeOutputName('bad:name.js'), 'bad_name.js')
assert.equal(textOutput('hello', 'JavaScript').name, 'output.js')
assert.equal(textOutput('hi', 'HTML').preview, 'html')
assert.equal(textOutput('# hi', 'markdown').preview, 'markdown')
assert.equal(outputBytes('🦙'), 4)
assert.deepEqual(csvPreview('name,note\r\nCamelid,"line one\nline two, quoted ""word"""\r\n').rows, [['name', 'note'], ['Camelid','line one\nline two, quoted "word"']])
assert.equal(csvPreview('a\nb\nc', 2).truncated, true)
assert.match(csvPreview('a,"bad').error, /unclosed/)
assert.match(previewDocument('<script>bad()</script>'), /script-src 'none'/)
assert.ok(previewDocument('<script>bad()</script>').indexOf('Content-Security-Policy') < previewDocument('<script>bad()</script>').indexOf('<script>'))
assert.deepEqual(toolOutputs('not JSON'), [])
assert.deepEqual(toolOutputs({ content:[{type:'resource_link',uri:'https://example.invalid/private'}] }), [])
assert.equal(toolOutputs({content:[{type:'resource',resource:{uri:'mcp://files/report.csv',mimeType:'text/csv',text:'a,b'}}]})[0].name, 'report.csv')
assert.equal(toolOutputs({content:[{type:'image',mimeType:'image/png',data:'aGVsbG8='}]})[0].bytes,5)
assert.equal(toolOutputs({content:[{type:'image',mimeType:'text/html',data:'aGVsbG8='}]}).length,0)
console.log('Output smoke passed: formats, safe filenames, UTF-8 sizes, CSV, embedded resources, and preview CSP.')
